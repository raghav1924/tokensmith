  private static generateFastAPI(algorithm: JWTAlgorithm, issuer: string, audience: string): GeneratedMiddleware {
    const code = `# auth.py - FastAPI Python Hardened JWT Verification Dependency
# Generated by TokenSmith (https://jatinsh.netlify.app/)
import os
import time
from fastapi import Request, HTTPException, status, Depends
from fastapi.security import HTTPBearer, HTTPAuthorizationCredentials
import jwt

JWT_SECRET = os.getenv("JWT_SECRET", "change-me-in-production")
EXPECTED_ALG = "${algorithm}"
EXPECTED_ISS = "${issuer}"
EXPECTED_AUD = "${audience}"

security = HTTPBearer()

async def verify_jwt(credentials: HTTPAuthorizationCredentials = Depends(security)):
    token = credentials.credentials
    try:
        # Enforce strict algorithm pinning and claim validation
        payload = jwt.decode(
            token,
            JWT_SECRET,
            algorithms=[EXPECTED_ALG],
            issuer=EXPECTED_ISS if EXPECTED_ISS else None,
            audience=EXPECTED_AUD if EXPECTED_AUD else None,
            options={"require": ["exp", "iat"]}
        )
        return payload
    except jwt.ExpiredSignatureError:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Token has expired"
        )
    except jwt.InvalidAlgorithmError:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Rejected unsupported algorithm"
        )
    except jwt.PyJWTError as e:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail=f"Token verification failed: {str(e)}"
        )
`;
    return {
      framework: 'fastapi',
      title: 'FastAPI Python Hardened JWT Dependency',
      filename: 'auth.py',
      code,
      instructions: 'Protect endpoints using `Depends(verify_jwt)`.'
    };
  }
